[GenerateTypedNameReferences]
public sealed partial class DrawingTabletWindow : FancyWindow
{
    private DrawingColorSampler? _sampler;
    private DrawingBrush _normalBrush;
    private byte _normalSize;
    private byte _normalOpacity;
    private byte _pixelSize = 1;
    private readonly Label _pixelSizeLabel = new() { HorizontalExpand = true, Visible = false };
    private readonly List<Color> _recent = [];
    private readonly IInputManager _input = IoCManager.Resolve<IInputManager>();
    private readonly IResourceManager _resources = IoCManager.Resolve<IResourceManager>();
    private static readonly ResPath GeometryPath = new("/drawing-tablet-window.txt");

    public void RestoreGeometry()
    {
        if (Parent == null || !_resources.UserData.TryReadAllText(GeometryPath, out var saved))
            return;
        var parts = saved.Split(' ');
        var values = new float[4];
        if (parts.Length != 4)
            return;
        for (var i = 0; i < 4; i++)
        {
            if (!float.TryParse(parts[i], NumberStyles.Float, CultureInfo.InvariantCulture, out values[i]) || !float.IsFinite(values[i]))
                return;
        }
        SetSize = Vector2.Clamp(new Vector2(values[2], values[3]), MinSize, Vector2.Max(MinSize, Parent.Size));
        LayoutContainer.SetPosition(this, Vector2.Clamp(new Vector2(values[0], values[1]), Vector2.Zero, Vector2.Max(Vector2.Zero, Parent.Size - SetSize)));
    }

    protected override void ExitedTree()
    {
        _sampler?.Close();
        if (Size.X > 0 && Size.Y > 0)
        {
            // The explicit array avoids a params-span helper that the client sandbox rejects.
            var value = string.Join(" ", new string[]
            {
                Position.X.ToString(CultureInfo.InvariantCulture), Position.Y.ToString(CultureInfo.InvariantCulture),
                Size.X.ToString(CultureInfo.InvariantCulture), Size.Y.ToString(CultureInfo.InvariantCulture),
            });
            _resources.UserData.WriteAllText(GeometryPath, value);
        }
        base.ExitedTree();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        var pointer = _input.MouseScreenPosition;
        var inside = Window?.Id == pointer.Window && ((UIBox2) GlobalPixelRect).Contains(pointer.Position);
        Modulate = Color.White.WithAlpha(inside ? 1f : 0.2f);
    }

    private sealed class ResizeGrip : Control
    {
        protected override void Draw(DrawingHandleScreen handle)
        {
            base.Draw(handle);
            var corner = (Vector2) PixelSize - new Vector2(2);
            for (var offset = 3; offset <= 12; offset += 3)
                handle.DrawLine(corner - new Vector2(offset, 0), corner - new Vector2(0, offset), Color.Gray);
        }
    }

    private readonly FloatSpinBox _size = new(1, 0) { HorizontalExpand = true };
    private readonly FloatSpinBox _opacity = new(1, 0) { HorizontalExpand = true };
    private bool _overheated;
    private bool _synchronized;
    private bool _actionPending;
    private int _pending;
    private int _strokes;
    private int _maxStrokes = DrawingTabletSettings.MaximumDrawingStrokes;
    private int _points;
    private int _maxPoints = DrawingTabletSettings.MaximumDrawingPoints;
    private int _maxRenderWork = DrawingTabletSettings.MaximumDrawingRenderWork;
    private bool _canRedo;
    private readonly StyleBoxFlat _colorSwatch = new() { BackgroundColor = Color.Black, BorderColor = Color.Gray };

    public event Action<DrawingStroke>? StrokeCompleted;
    public event Action<DrawingTabletAction>? ActionRequested;

    public DrawingTabletWindow()
    {
        RobustXamlLoader.Load(this);
        AddChild(new ResizeGrip { MouseFilter = MouseFilterMode.Ignore });
        _colorSwatch.BorderThickness = new Thickness(1);
        CurrentColor.PanelOverride = _colorSwatch;
        SizeInput.AddChild(_size);
        SizeInput.AddChild(_pixelSizeLabel);
        OpacityInput.AddChild(_opacity);
        SizeSlider.Rounded = OpacitySlider.Rounded = true;
        _size.Value = Canvas.BrushSize;
        _opacity.Value = Canvas.Opacity;
        SizeSlider.OnValueChanged += args =>
        {
            if (Canvas.PixelArt)
                SetBrushSize(DrawingRaster.PixelGridSizes[Math.Clamp((int) MathF.Round(args.Value) - 1, 0, DrawingRaster.PixelGridSizes.Length - 1)]);
            else
                SetBrushSize(args.Value);
        };
        OpacitySlider.OnValueChanged += args => SetOpacity(args.Value);
        _size.OnValueChanged += args => SetBrushSize(args.Value);
        _opacity.OnValueChanged += args => SetOpacity(args.Value);
        DrawTool.OnPressed += _ => SetTool(DrawingTool.Draw);
        EraseTool.OnPressed += _ => SetTool(DrawingTool.Erase);
        SampleTool.OnPressed += _ => BeginSampling();
        PixelMode.OnPressed += _ => SetPixelMode(!Canvas.PixelArt);
        CircleBrush.OnPressed += _ => SetBrush(DrawingBrush.Circle);
        SquareBrush.OnPressed += _ => SetBrush(DrawingBrush.Square);
        ColorPicker.OnColorChanged += SetInk;
        ColorPicker.Color = Color.Black;
        Canvas.PointCountChanged += points => { _points = points; UpdatePointCount(); };
        Canvas.ColorSampled += color =>
        {
            ColorPicker.Color = color;
            SetInk(color);
            _sampler?.Close();
        };
        Canvas.SamplingCancelled += () => _sampler?.Close();
        Canvas.StrokeCompleted += stroke =>
        {
            _strokes++;
            _canRedo = false;
            if (!stroke.Erase)
                RememberColor(stroke.Color);
            StrokeCompleted?.Invoke(stroke);
            UpdateControls();
        };
        UndoButton.OnPressed += _ => Request(DrawingTabletAction.Undo);
        RedoButton.OnPressed += _ => Request(DrawingTabletAction.Redo);
        ClearButton.OnPressed += _ => Request(DrawingTabletAction.Clear);
        PrintButton.OnPressed += _ => Request(DrawingTabletAction.Print);
        SetTool(DrawingTool.Draw);
        SetBrush(DrawingBrush.Circle);
        RefreshColors();
        UpdateControls();
    }

    private void BeginSampling()
    {
        Canvas.FinishStroke();
        _sampler?.Close();
        SetTool(DrawingTool.Sample);
        var sampler = new DrawingColorSampler(Canvas);
        _sampler = sampler;
        sampler.OnPopupHide += () =>
        {
            sampler.Orphan();
            if (_sampler != sampler)
                return;
            _sampler = null;
            SetTool(DrawingTool.Draw);
        };
        sampler.OpenOverCanvas();
    }

    private void SetPixelMode(bool enabled)
    {
        Canvas.FinishStroke();
        if (!enabled)
            _pixelSize = Canvas.BrushSize;
        if (enabled)
        {
            _normalBrush = Canvas.Brush;
            _normalSize = Canvas.BrushSize;
            _normalOpacity = Canvas.Opacity;
        }
        Canvas.PixelArt = enabled;
        SizeSlider.MaxValue = enabled ? DrawingRaster.PixelGridSizes.Length : DrawingRaster.MaximumBrushSize;
        PixelMode.Text = Loc.GetString(enabled ? "drawing-tablet-vector-mode" : "drawing-tablet-pixel-mode");
        SetBrush(enabled ? DrawingBrush.Square : _normalBrush);
        SetBrushSize(enabled ? _pixelSize : _normalSize);
        SetOpacity(enabled ? 100 : _normalOpacity);
        CircleBrush.Disabled = enabled;
        SquareBrush.Disabled = false;
        OpacitySlider.Disabled = enabled;
        _size.Visible = !enabled;
        _pixelSizeLabel.Visible = enabled;
        SetSpinEnabled(_opacity, !enabled);
    }

    private static void SetSpinEnabled(FloatSpinBox spin, bool enabled)
    {
        foreach (var child in spin.Children)
        {
            if (child is Button button)
                button.Disabled = !enabled;
            if (child is LineEdit entry)
                entry.Editable = enabled;
        }
    }

    private void SetBrushSize(float size)
    {
        var value = Math.Clamp(MathF.Round(size), 1, DrawingRaster.MaximumBrushSize);
        var pixelIndex = 0;
        if (Canvas.PixelArt)
        {
            for (var i = 1; i < DrawingRaster.PixelGridSizes.Length; i++)
            {
                if (MathF.Abs(DrawingRaster.PixelGridSizes[i] - value) < MathF.Abs(DrawingRaster.PixelGridSizes[pixelIndex] - value))
                    pixelIndex = i;
            }
            value = DrawingRaster.PixelGridSizes[pixelIndex];
        }
        Canvas.BrushSize = (byte) value;
        _pixelSizeLabel.Text = $"{(int) value}x{(int) value}";
        SizeSlider.SetValueWithoutEvent(Canvas.PixelArt ? pixelIndex + 1 : value);
        if (_size.Value != value)
            _size.Value = value;
    }

    private void SetOpacity(float opacity)
    {
        var value = Math.Clamp(MathF.Round(opacity), 1, 100);
        Canvas.Opacity = (byte) value;
        OpacitySlider.SetValueWithoutEvent(value);
        if (_opacity.Value != value)
            _opacity.Value = value;
    }

    private void SetTool(DrawingTool tool)
    {
        Canvas.Tool = tool;
        Canvas.DefaultCursorShape = tool == DrawingTool.Sample ? CursorShape.Crosshair : CursorShape.Arrow;
        DrawTool.Pressed = tool == DrawingTool.Draw;
        EraseTool.Pressed = tool == DrawingTool.Erase;
        SampleTool.Pressed = tool == DrawingTool.Sample;
    }

    private void SetBrush(DrawingBrush brush)
    {
        Canvas.Brush = brush;
        CircleBrush.Pressed = brush == DrawingBrush.Circle;
        SquareBrush.Pressed = brush == DrawingBrush.Square;
    }

    private void RememberColor(Color color)
    {
        color = color.WithAlpha(1f);
        _recent.Remove(color);
        _recent.Insert(0, color);
        if (_recent.Count > 10)
            _recent.RemoveAt(10);
        RefreshColors();
    }

    private void RefreshColors()
    {
        RecentColors.RemoveAllChildren();
        for (var i = 0; i < 10; i++)
        {
            var color = i < _recent.Count ? _recent[i] : (Color?) null;
            var button = new Button { HorizontalExpand = true, MinSize = new Vector2(0, 24), Disabled = color == null,
                ToolTip = color is { } previewColor ? previewColor.ToHex() : null };
            button.AddStyleClass(StyleClass.ButtonSmall);
            button.AddChild(new PanelContainer
            {
                PanelOverride = new StyleBoxFlat { BackgroundColor = color ?? Color.Transparent },
                MinSize = new Vector2(12, 12), MouseFilter = MouseFilterMode.Ignore,
            });
            button.OnPressed += _ => { if (color is { } ink) { ColorPicker.Color = ink; SetInk(ink); } };
            RecentColors.AddChild(button);
        }
    }

    private void Request(DrawingTabletAction action)
    {
        Canvas.FinishStroke();
        _actionPending = true;
        ActionRequested?.Invoke(action);
        UpdateControls();
    }

    private void SetInk(Color color)
    {
        Canvas.Ink = color.WithAlpha(1f);
        _colorSwatch.BackgroundColor = Canvas.Ink;
    }

    public void SetDocument(DrawingTabletState state)
    {
        var wasOverheated = _overheated;
        _overheated = state.Overheated;
        if (_overheated)
            _sampler?.Close();
        Canvas.SetDocument(state.Strokes);
        if (_overheated || wasOverheated)
            ShowNotice(_overheated ? Loc.GetString("drawing-tablet-overheated") : string.Empty);
        _strokes = state.Strokes.Count;
        _maxStrokes = state.MaxStrokes;
        _maxPoints = state.MaxPoints;
        _maxRenderWork = state.MaxRenderWork;
        _canRedo = state.CanRedo;
        _synchronized = true;
        _actionPending = false;
        _pending = 0;
        // Recent colors are rebuilt from the drawing's latest strokes.
        _recent.Clear();
        for (var i = state.Strokes.Count - 1; i >= 0 && _recent.Count < 10; i--)
        {
            var stroke = state.Strokes[i];
            var ink = stroke.Color.WithAlpha(1f);
            if (!stroke.Erase && !_recent.Contains(ink))
                _recent.Add(ink);
        }
        RefreshColors();
        UpdateControls();
    }

    public void FinishStroke() => Canvas.FinishStroke();

    public void RestorePendingStroke(DrawingStroke stroke)
    {
        Canvas.RestorePendingStroke(stroke);
        _strokes++;
        _canRedo = false;
        UpdateControls();
    }

    public void SetPending(int count, bool actionPending)
    {
        _pending = count;
        _actionPending = actionPending;
        UpdateControls();
    }

    public void ShowNotice(string text)
    {
        if (_overheated)
            text = Loc.GetString("drawing-tablet-overheated");
        Status.SetMessage(text);
        Status.ToolTip = text;
        Status.Visible = !string.IsNullOrEmpty(text);
    }

    private void UpdateControls()
    {
        SampleTool.Disabled = _overheated;
        UpdatePointCount();
        Canvas.CanDraw = !_overheated && _synchronized && !_actionPending && _pending < DrawingTabletSettings.MaximumPendingClientStrokes && _strokes < _maxStrokes;
        var waiting = _overheated || !_synchronized || _actionPending || _pending > 0;
        UndoButton.Disabled = waiting || _strokes == 0;
        RedoButton.Disabled = waiting || !_canRedo;
        ClearButton.Disabled = waiting || _strokes == 0;
        PrintButton.Disabled = waiting;
    }

    private void UpdatePointCount()
        => PointCount.Text = Loc.GetString("drawing-tablet-point-count",
            ("count", DrawingTabletComplexity.Calculate(Canvas.ComplexityStrokeCount, _points,
                Canvas.ComplexityRenderWork, _maxStrokes, _maxPoints, _maxRenderWork).ToString("N0", CultureInfo.InvariantCulture)),
            ("limit", _maxPoints.ToString("N0", CultureInfo.InvariantCulture)));
}
